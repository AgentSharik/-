DOSSIER = 6.0 * 7
POSTER = 10.0

rows, t = [], 0.0
for s in SHOTS:
    sid, act, kind, text = s[0], s[1], s[2], s[3]
    if kind == "vo":
        vo = MEASURED.get(sid, vo_est(text))
        dur = vo + LEAD + TAIL
        if sid == "SH-02":
            dur = 4.5 + vo + 1.6      # немой пролог печати + VO + хвост
        note = f"VO {vo:.2f} c" + (" (замер)" if sid in MEASURED else " (оценка)")
    else:
        cps = 13.0
        chars = len(text.replace(" :: ", "\n"))
        dur = s[4] if len(s) > 4 else chars / cps + 2.2
        note = f"печать {chars} зн @ {cps:.0f} зн/с"
    rows.append(dict(id=sid, act=act, dur=round(dur, 2), start=round(t, 2),
                     end=round(t + dur, 2), frames=int(round(dur * 30)), note=note))
    t += dur
for i in range(7):
    rows.append(dict(id=f"DOSSIER-{i+1}", act=7, dur=6.0, start=round(t, 2),
                     end=round(t + 6, 2), frames=180, note="карточка досье"))
    t += 6.0
rows.append(dict(id="POSTER", act=8, dur=10.0, start=round(t, 2), end=round(t + 10, 2),
                 frames=300, note="постер + титр"))
t += 10.0

def mmss(x): return f"{int(x)//60}:{int(x)%60:02d}"

acts = {}
for r in rows:
    acts.setdefault(r["act"], 0.0)
    acts[r["act"]] += r["dur"]

